import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import path from "node:path";

const require = createRequire(import.meta.url);
const requireFromNext = createRequire(require.resolve("next/package.json"));
const sharp = requireFromNext("sharp");
const root = fileURLToPath(new URL("../", import.meta.url));
const output = path.join(root, "public/donetsk/images");
const names = ["front", "stretcher-side", "passenger-seats", "stretcher-rear"];
const images = {};

await mkdir(output, { recursive: true });

for (const name of names) {
  const input = path.join(root, "public/donetsk/moskva", `${name}.webp`);
  const { width, height } = await sharp(input).metadata();
  const widths = [...new Set([384, 640, 960, width].filter((size) => size <= width))];
  const formats = {};

  for (const format of ["avif", "webp"]) {
    const variants = [];
    for (const size of widths) {
      const image = sharp(input).resize({ width: size, withoutEnlargement: true });
      // Keep the full-size supplied WebP byte-for-byte; only encode responsive copies.
      const buffer = format === "webp" && size === width
        ? await readFile(input)
        : await (format === "avif"
          ? image.avif({ quality: 60, effort: 6 })
          : image.webp({ quality: 86, effort: 6 })).toBuffer();
      const hash = createHash("sha256").update(buffer).digest("hex").slice(0, 12);
      const filename = `mercedes-${name}-${size}-${hash}.${format}`;
      await writeFile(path.join(output, filename), buffer);
      variants.push({ src: `/donetsk/images/${filename}`, width: size });
    }
    formats[format] = variants;
  }

  images[name] = { width, height, ...formats };
}

await writeFile(
  path.join(root, "app/donetsk/moskva/mercedes-images.generated.ts"),
  `// Generated by scripts/optimize-mercedes-images.mjs. Do not edit by hand.\nexport const mercedesImages = ${JSON.stringify(images, null, 2)} as const;\n`,
);
