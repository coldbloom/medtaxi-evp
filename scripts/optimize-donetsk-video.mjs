import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Run explicitly when replacing the source video; committed output needs no FFmpeg at build time.
// Usage: FFMPEG_PATH=/path/to/ffmpeg node scripts/optimize-donetsk-video.mjs
const ffmpeg = process.env.FFMPEG_PATH || "ffmpeg";
const require = createRequire(import.meta.url);
const requireFromNext = createRequire(require.resolve("next/package.json"));
const sharp = requireFromNext("sharp");
const root = fileURLToPath(new URL("../", import.meta.url));
const source = path.join(root, "public/donetsk/video/stretcher-on-lift.mp4");
const output = path.join(root, "public/donetsk/video/generated");
const temporary = await mkdtemp(path.join(tmpdir(), "medtaxi-video-"));

function encode(args) {
  execFileSync(ffmpeg, ["-hide_banner", "-loglevel", "error", "-nostdin", "-y", ...args], {
    stdio: ["ignore", "ignore", "inherit"],
  });
}

async function save(buffer, label, extension) {
  const hash = createHash("sha256").update(buffer).digest("hex").slice(0, 12);
  const filename = `stretcher-on-lift-${label}-${hash}.${extension}`;
  await writeFile(path.join(output, filename), buffer);
  console.log(`${filename}: ${buffer.length} bytes`);
  return { src: `/donetsk/video/generated/${filename}`, bytes: buffer.length };
}

try {
  await mkdir(output, { recursive: true });
  const posterFrame = path.join(temporary, "poster.png");
  encode(["-i", source, "-map", "0:v:0", "-an", "-frames:v", "1", "-vf", "scale=540:960:flags=lanczos,setsar=1", posterFrame]);
  const poster = await save(await sharp(posterFrame).webp({ quality: 72, effort: 6 }).toBuffer(), "poster-540", "webp");
  const manifest = { poster: { ...poster, width: 540, height: 960 } };

  for (const [name, width, height] of [["mobile", 540, 960], ["desktop", 720, 1280]]) {
    const variant = { width, height };
    for (const format of ["webm", "mp4"]) {
      const destination = path.join(temporary, `${name}.${format}`);
      const encoding = format === "webm"
        ? ["-c:v", "libvpx-vp9", "-b:v", "0", "-crf", "43", "-deadline", "good", "-cpu-used", "2", "-row-mt", "1"]
        : ["-c:v", "libx264", "-crf", "30", "-preset", "slow", "-movflags", "+faststart"];
      encode([
        "-i", source, "-map", "0:v:0", "-an", "-sn", "-dn", "-map_metadata", "-1", "-map_chapters", "-1",
        "-vf", `scale=${width}:${height}:flags=lanczos,setsar=1`,
        "-r", "30", "-pix_fmt", "yuv420p", "-g", "60", "-fflags", "+bitexact", ...encoding, destination,
      ]);
      variant[format] = await save(await readFile(destination), `${name}-${width}`, format);
    }
    manifest[name] = variant;
  }

  await writeFile(
    path.join(root, "app/donetsk/video.generated.ts"),
    `// Generated by scripts/optimize-donetsk-video.mjs. Do not edit by hand.\nexport const donetskHeroVideo = ${JSON.stringify(manifest, null, 2)} as const;\n`,
  );
} finally {
  await rm(temporary, { recursive: true, force: true });
}
